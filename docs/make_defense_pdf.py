def prf(d, k):
    x = d.get(k) or {}
    return f"{x.get('precision', 0):.3f}", f"{x.get('recall', 0):.3f}", f"{x.get('f1', 0):.3f}", f"{x.get('matched', 0)}/{x.get('pred', 0)}/{x.get('gold', 0)}"


def chk(k):
    d = CHK.get(k) or {}
    r = d.get("report") or {}
    q = r.get("quotes")
    tail = [l for l in (d.get("stdout_tail") or "").splitlines() if l.startswith("таблиц")]
    if q:
        quotes = f"{q['matched']} / {q['requested']}"
    elif tail:
        quotes = tail[-1].split("проверено цитат:")[-1].replace("не найдено", "не найдено").strip()
    else:
        quotes = "—"
    return str(d.get("exit_code", "—")), str(d.get("n_errors", 0) or 0), quotes


# ---------------------------------------------------------------- pipeline diagram
def pipeline_diagram():
    w, h = 175 * mm, 118 * mm
    d = Drawing(w, h)
    steps = [("PDF", "регистрация, SHA-256"), ("Текстовый слой", "pypdf + PyMuPDF"), ("OCR", "Tesseract, только сканы"),
             ("Сегментация", "разделы, подписи, таблицы"), ("Ноды извлечения", "R  A  B  C  V"), ("Журнал нод", "промпт, ответ, модель"),
             ("Нормализация", "raw сохраняется"), ("Проверка источника", "цитата, строка, ячейка"), ("Кворум", "A vs B (или R), C"),
             ("Предметные правила", "PCE, Voc<Eg, шкалы..."), ("Статус", "verified / flagged / review"), ("БД + аудит", "SQLite, история"),
             ("UI и админка", "поиск, источник, очередь"), ("Экспорт", "CSV по шаблонам комплектов"), ("Проверщики", "check_submission.py")]
    bw, bh = 52 * mm, 13 * mm
    cols = [6 * mm, 61.5 * mm, 117 * mm]
    for i, (a, b) in enumerate(steps):
        c, r = i % 3, i // 3
        if r % 2 == 1:
            c = 2 - c  # snake layout
        x, y = cols[c], h - 8 * mm - r * 22 * mm - bh
        fill = TEALBG if i in (7, 8, 9, 10) else (AMBERBG if i in (4,) else colors.HexColor("#eef2f7"))
        d.add(Rect(x, y, bw, bh, rx=6, ry=6, fillColor=fill, strokeColor=INK, strokeWidth=0.6))
        d.add(String(x + 4, y + bh - 5 * mm, f"{i + 1}. {a}", fontName="Arial-Bold", fontSize=8.6, fillColor=INK))
        d.add(String(x + 4, y + 3 * mm, b, fontName="Arial", fontSize=7.4, fillColor=colors.HexColor("#33496b")))
        if i < len(steps) - 1:
            nc, nr = (i + 1) % 3, (i + 1) // 3
            if nr % 2 == 1:
                nc = 2 - nc
            if nr == r:  # horizontal arrow
                x1 = x + bw if nc > c else x
                x2 = cols[nc] if nc > c else cols[nc] + bw
                yy = y + bh / 2
                d.add(Line(x1, yy, x2, yy, strokeColor=INK, strokeWidth=0.8))
                s = 1 if nc > c else -1
                d.add(Polygon([x2, yy, x2 - s * 4, yy + 2.5, x2 - s * 4, yy - 2.5], fillColor=INK, strokeColor=INK))
            else:  # down arrow
                xx = x + bw / 2
                d.add(Line(xx, y, xx, y - (22 * mm - bh), strokeColor=INK, strokeWidth=0.8))
                yy = y - (22 * mm - bh)
                d.add(Polygon([xx, yy, xx - 2.5, yy + 4, xx + 2.5, yy + 4], fillColor=INK, strokeColor=INK))
    return d


def chain_diagram():
    w, h = 175 * mm, 30 * mm
    d = Drawing(w, h)
    boxes = [("Основной провайдер", "модель ноды"), ("Klinch claude-haiku-5-5", "ключ 1 → ключ 2"),
             ("Klinch gpt-6-luna", "ключ 1 → ключ 2"), ("Локальный Claude Code", "claude -p, без изображений")]
