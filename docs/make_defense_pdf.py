        d.add(Rect(x, 6 * mm, bw, 17 * mm, rx=6, ry=6, fillColor=TEALBG if i else colors.HexColor("#eef2f7"), strokeColor=INK, strokeWidth=0.6))
        d.add(String(x + 3, 17 * mm, a, fontName="Arial-Bold", fontSize=7.6, fillColor=INK))
        d.add(String(x + 3, 10 * mm, b, fontName="Arial", fontSize=7, fillColor=colors.HexColor("#33496b")))
